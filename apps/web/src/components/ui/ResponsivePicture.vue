<template>
  <picture class="contents">
    <source type="image/avif" :srcset="srcset('avif')" :sizes="sizes">
    <source type="image/webp" :srcset="srcset('webp')" :sizes="sizes">
    <img
      :src="file(photo.widths[0], 'jpg')"
      :srcset="srcset('jpg')"
      :sizes="sizes"
      :width="photo.width"
      :height="photo.height"
      :alt="alt ?? photo.alt"
      :loading="priority ? 'eager' : 'lazy'"
      :fetchpriority="priority ? 'high' : undefined"
      decoding="async"
      :class="imgClass"
    >
  </picture>
</template>

<script setup>
// A course photo from src/data/photos.js (generated by scripts/gen-photos.py) as <picture> with AVIF, WebP and JPEG
// srcsets, intrinsic width/height (no layout shift) and lazy loading. Heroes and other above-the-fold photos pass
// `priority` (eager, fetchpriority high, for LCP).
//   <ResponsivePicture name="course-4" sizes="100vw" priority img-class="absolute inset-0 w-full h-full object-cover" />
// `sizes` should describe the rendered width (e.g. "(min-width: 768px) 33vw, 100vw"). `alt` overrides the
// manifest's alt text; pass alt="" for a purely decorative photo.
import { computed } from 'vue'
import { photos } from '@/data/photos'

const props = defineProps({
  name:     { type: String, required: true },
  sizes:    { type: String, default: '100vw' },
  alt:      { type: String, default: undefined },
  priority: { type: Boolean, default: false },
  imgClass: { type: [String, Array, Object], default: 'w-full h-auto' },
})

const photo = computed(() => {
  const p = photos[props.name]
  if (!p) throw new Error(`Unknown photo "${props.name}" (see src/data/photos.js)`)
  return p
})

function file(width, ext) {
  return `/images/photos/${props.name}-${width}.${ext}`
}
function srcset(ext) {
  return photo.value.widths.map(w => `${file(w, ext)} ${w}w`).join(', ')
}
</script>
