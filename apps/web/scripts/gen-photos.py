"""Responsive course photos: AVIF + WebP + JPEG at 640/1280/1920 px wide (never wider than the original), plus
src/data/photos.js with each photo's size, so pages can render <picture> with srcset, width and height.

Originals live in apps/web/photos-src (not deployed). Add or replace a photo there, give it alt text in ALT below,
then run from apps/web:  python scripts/gen-photos.py
"""
import json
import os
from PIL import Image, ImageOps

SRC = 'photos-src'
OUT = 'public/images/photos'
WIDTHS = [640, 1280, 1920]
ALT = {
    'course-hero': 'Sunlit fairway at Deer Run Golf Course with the treeline beyond',
    'course-2': 'Two golfers on the tee box with the green and a wall of hardwoods behind',
    'course-2-wide': 'Two golfers on the tee box at Deer Run',
    'course-3': 'A green at Deer Run Golf Course',
    'course-4': 'Rolling fairways of Deer Run Golf Course',
    'course-5': 'Golf ball on the fairway at sunset with the flag and the ridge behind',
    'course-5-wide': 'Sunset over the green at Deer Run with the Bankhead ridge in the distance',
}

os.makedirs(OUT, exist_ok=True)
manifest = {}
for file in sorted(os.listdir(SRC)):
    name, ext = os.path.splitext(file)
    if ext.lower() not in ('.jpg', '.jpeg', '.png'):
        continue
    img = ImageOps.exif_transpose(Image.open(os.path.join(SRC, file))).convert('RGB')
    widths = sorted({w for w in WIDTHS if w < img.width} | {min(img.width, WIDTHS[-1])})
    for w in widths:
        h = round(img.height * w / img.width)
        sized = img.resize((w, h), Image.LANCZOS)
        base = os.path.join(OUT, f'{name}-{w}')
        # AVIF at 45 (was 55): about 30% smaller, no visible difference at these sizes (Lighthouse Phase 7 pass)
        sized.save(base + '.avif', 'AVIF', quality=45, speed=6)
        sized.save(base + '.webp', 'WEBP', quality=72, method=6)
        sized.save(base + '.jpg', 'JPEG', quality=78, optimize=True, progressive=True)
    manifest[name] = {'width': img.width, 'height': img.height, 'widths': widths, 'alt': ALT.get(name, '')}
    print(name, img.size, widths)

with open('src/data/photos.js', 'w', encoding='utf-8') as f:
    f.write('// Generated by scripts/gen-photos.py: course photos in public/images/photos (AVIF/WebP/JPEG per width).\n')
    f.write('// Render them with components/ui/ResponsivePicture.vue: <ResponsivePicture name="course-4" sizes="100vw" />\n')
    f.write('export const photos = ' + json.dumps(manifest, indent=2) + '\n')
